/**
 * Regenerates the brand assets that cannot be rendered at request time:
 *   - src/v2/brand/summit-still.ts, the summit scene as a standalone SVG string
 *     for the social card (the renderer takes an image, not React);
 *   - src/app/icon.svg, the favicon (the goat's head in gold on dark).
 *
 * Run `npm run brand:assets` after changing goat-paths.ts or SummitScene.tsx.
 * src/v2/brand/brand.test.tsx fails when summit-still.ts is stale.
 */

import { writeFileSync } from 'node:fs';
import path from 'node:path';

import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

import { BODY, EAR, EYE, HORN_FAR, HORN_NEAR } from '../src/v2/brand/goat-paths';
import { SummitScene } from '../src/v2/brand/SummitScene';

const root = path.resolve(__dirname, '..');

const still = renderToStaticMarkup(createElement(SummitScene, { still: true }));
writeFileSync(
  path.join(root, 'src/v2/brand/summit-still.ts'),
  `// Generated by scripts/build-brand-assets.ts. Do not edit by hand.\nexport const SUMMIT_STILL_SVG =\n  ${JSON.stringify(still)};\n`,
);

const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#fff4d4"/>
      <stop offset="0.55" stop-color="#e9c46a"/>
      <stop offset="1" stop-color="#b98a2e"/>
    </linearGradient>
  </defs>
  <rect width="64" height="64" rx="14" fill="#0c0e17"/>
  <rect x="1" y="1" width="62" height="62" rx="13" fill="none" stroke="#e9c46a" stroke-opacity="0.35" stroke-width="2"/>
  <g transform="translate(8 10) scale(0.25) translate(-130 56)">
    <path d="${HORN_FAR}" fill="#b98a2e"/>
    <path d="${BODY}" fill="url(#g)"/>
    <path d="${HORN_NEAR}" fill="url(#g)"/>
    <path d="${EAR}" fill="url(#g)"/>
    <circle cx="${EYE.x}" cy="${EYE.y}" r="4" fill="#0c0e17"/>
  </g>
</svg>
`;
writeFileSync(path.join(root, 'src/app/icon.svg'), icon);

console.log('wrote src/v2/brand/summit-still.ts and src/app/icon.svg');
